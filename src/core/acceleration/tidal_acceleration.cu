// =============================================================================
// Binary File Format for Earth Position Data
// =============================================================================

struct EarthPositionHeader {
    char magic[8];                   // "EARTHPOS"
    uint32_t version;                // File format version
    uint32_t num_frames;             // Number of time frames
    float time_start;                // Start time (seconds from epoch)
    float time_interval;             // Time between frames (typically 60s)
    double perturber_mass;           // Mass of perturber (kg)
    uint8_t reserved[8];             // Future use

    EarthPositionHeader()
        : version(1), num_frames(0), time_start(0), time_interval(60.0f),
          perturber_mass(5.972e24) {  // Earth mass
        memcpy(magic, "EARTHPOS", 8);
        memset(reserved, 0, sizeof(reserved));
    }
};

// Single frame of Earth position data (in body-fixed frame)
struct EarthPositionFrame {
    double R_c_x, R_c_y, R_c_z;      // Position vector (meters)
    double R_c_mag;                   // |R_c| for convenience
};
static_assert(sizeof(EarthPositionHeader) == 40, "EARTHPOS v1 must remain a 40-byte little-endian record");
static_assert(sizeof(EarthPositionFrame) == 32, "EARTHPOS v1 frame size changed");

// =============================================================================
// Earth Position Data Buffer
// =============================================================================

struct EarthPositionBuffer {
    // Host staging buffers
    std::vector<float> h_times;
    std::vector<double> h_R_c_x, h_R_c_y, h_R_c_z;
    std::vector<double> h_R_c_mag;

    // Current interpolated values
    double current_R_c_x, current_R_c_y, current_R_c_z;
    double current_R_c_mag;

    // Loaded range
    int32_t loaded_start_frame;
    int32_t loaded_num_frames;

    // File info
    int32_t total_frames;
    float time_start;
    float time_interval;
    double perturber_mass;

    // Batch size
    int32_t batch_size;

    EarthPositionBuffer()
        : current_R_c_x(0), current_R_c_y(0), current_R_c_z(0),
          current_R_c_mag(1.0e10),  // Large default to avoid singularity
          loaded_start_frame(-1), loaded_num_frames(0),
          total_frames(0), time_start(0), time_interval(60.0f),
          perturber_mass(5.972e24), batch_size(1000) {}

    void allocate(int32_t batch) {
        batch_size = batch;
        h_times.resize(batch);
        h_R_c_x.resize(batch);
        h_R_c_y.resize(batch);
        h_R_c_z.resize(batch);
        h_R_c_mag.resize(batch);
    }

    void clear() {
        h_times.clear();
        h_R_c_x.clear();
        h_R_c_y.clear();
        h_R_c_z.clear();
        h_R_c_mag.clear();
        loaded_start_frame = -1;
        loaded_num_frames = 0;
    }

    // Interpolate Earth position at given time
    void interpolate_at_time(float query_time) {
        if (loaded_num_frames <= 0) {
            throw std::runtime_error("EARTHPOS data were not loaded");
        }
        const float first = time_start;
        const float last = time_start + (total_frames - 1) * time_interval;
        if (!std::isfinite(query_time) || query_time < first || query_time > last)
            throw std::runtime_error("EARTHPOS data do not cover the requested simulation time");

        // Find bracketing frames
        float rel_time = (query_time - time_start) / time_interval;
        int frame_lo = static_cast<int>(rel_time) - loaded_start_frame;
        int frame_hi = frame_lo + 1;

        // Clamp to loaded range
        frame_lo = std::max(0, std::min(frame_lo, loaded_num_frames - 1));
        frame_hi = std::max(0, std::min(frame_hi, loaded_num_frames - 1));

        if (frame_lo == frame_hi) {
            current_R_c_x = h_R_c_x[frame_lo];
            current_R_c_y = h_R_c_y[frame_lo];
            current_R_c_z = h_R_c_z[frame_lo];
            current_R_c_mag = h_R_c_mag[frame_lo];
            return;
        }

        // Linear interpolation
        float t0 = time_start + (loaded_start_frame + frame_lo) * time_interval;
        float t1 = time_start + (loaded_start_frame + frame_hi) * time_interval;
        double alpha = (query_time - t0) / (t1 - t0);
        alpha = std::max(0.0, std::min(1.0, alpha));

        current_R_c_x = h_R_c_x[frame_lo] + alpha * (h_R_c_x[frame_hi] - h_R_c_x[frame_lo]);
        current_R_c_y = h_R_c_y[frame_lo] + alpha * (h_R_c_y[frame_hi] - h_R_c_y[frame_lo]);
        current_R_c_z = h_R_c_z[frame_lo] + alpha * (h_R_c_z[frame_hi] - h_R_c_z[frame_lo]);

        // Recompute magnitude (more accurate than interpolating magnitude)
        current_R_c_mag = sqrt(current_R_c_x * current_R_c_x +
                               current_R_c_y * current_R_c_y +
                               current_R_c_z * current_R_c_z);
    }
};

// =============================================================================
// GPU Constant Memory for Tidal Parameters
// =============================================================================

struct TidalParamsGPU {
    // Earth position relative to Apophis COM (body-fixed frame)
    double R_c_x, R_c_y, R_c_z;
    double R_c_mag;
    double R_c_mag_cubed;            // |R_c|³ for efficiency
    double R_c_mag_squared;          // |R_c|² for formula

    // Pre-computed factor: G * M_E / R_c³
    double tidal_factor;

    // Patch offset from Apophis center of mass
    double offset_x, offset_y, offset_z;

    // Gravitational constant (for reference)
    double G;

    // Perturber mass
    double perturber_mass;

    // Enable flag
    bool enabled;
};

__constant__ TidalParamsGPU dev_tidal_params;

// =============================================================================
// Tidal Acceleration Kernel
// =============================================================================
// Computes 1st-order tidal acceleration from external perturber:
//
//   a_t = (G * M_E / R_c³) * (3 * (R_c · r) / R_c² * R_c - r)
//
// Derivation: a_t = a_particle - a_COM
//   = G*M * [(R_c - r)/|R_c - r|³ - R_c/|R_c|³]
//   ≈ (G*M/R_c³) * (3(R_c·r)/R_c² * R_c - r)     [1st order in r/R_c]
//
// Physical interpretation:
//   - Along R_c direction:  stretching (a ∝ +2r, factor 2× stronger)
//   - Perpendicular to R_c: compression (a ∝ -r, squeezing)
//
// Where factor = G * M_E / R_c³
// =============================================================================

__global__ void compute_tidal_acceleration_kernel(
    // Particle positions (double precision)
    const double* __restrict__ pos_x,
    const double* __restrict__ pos_y,
    const double* __restrict__ pos_z,
    // Particle mass
    const float* __restrict__ mass,
    // Output forces
    double* __restrict__ force_x,
    double* __restrict__ force_y,
    double* __restrict__ force_z,
    int32_t num_particles
) {
    int idx = blockIdx.x * blockDim.x + threadIdx.x;
    if (idx >= num_particles) return;
    if (!dev_tidal_params.enabled) return;

    // Load particle position (relative to simulation box origin)
    double px = pos_x[idx];
    double py = pos_y[idx];
    double pz = pos_z[idx];

    float m = mass[idx];

    // CRITICAL: Transform to position relative to Apophis center of mass
    // r = offset + particle_position
    double rx = dev_tidal_params.offset_x + px;
    double ry = dev_tidal_params.offset_y + py;
    double rz = dev_tidal_params.offset_z + pz;

    // Load Earth position (body-fixed frame)
    double R_c_x = dev_tidal_params.R_c_x;
    double R_c_y = dev_tidal_params.R_c_y;
    double R_c_z = dev_tidal_params.R_c_z;
    double R_c_sq = dev_tidal_params.R_c_mag_squared;
    double factor = dev_tidal_params.tidal_factor;

    // -------------------------------------------------------------------------
    // Compute 1st-order tidal acceleration
    // a_t = factor * (3 * (R_c · r) / R_c² * R_c - r)
    // -------------------------------------------------------------------------
    double R_c_dot_r = R_c_x * rx + R_c_y * ry + R_c_z * rz;

    // 3 * (R_c · r) / R_c²
    double coeff = 3.0 * R_c_dot_r / R_c_sq;

    // a_t = factor * (coeff * R_c - r)
    double ax = factor * (coeff * R_c_x - rx);
    double ay = factor * (coeff * R_c_y - ry);
    double az = factor * (coeff * R_c_z - rz);

    // Convert to force and add to existing forces
    atomic_add_force(force_x, force_y, force_z, m * ax, m * ay, m * az, idx);
}

// =============================================================================
// Tidal Acceleration Manager
// =============================================================================

class TidalAccelerationManager {
public:
    EarthPositionBuffer earth_buffer;
    std::ifstream data_file;
    EarthPositionHeader header;

    // Configuration
    bool enabled;
    LoadMethod load_method;
    double perturber_mass;

    // Patch offset (from DomainConfig)
    double offset_x, offset_y, offset_z;

    // State
    bool initialized;
    bool data_loaded;

    TidalAccelerationManager()
        : enabled(false), load_method(LoadMethod::ONCE),
          perturber_mass(5.972e24),
          offset_x(0), offset_y(0), offset_z(0),
          initialized(false), data_loaded(false) {}

    ~TidalAccelerationManager() {
        shutdown();
    }

    // =========================================================================
    // Initialization
    // =========================================================================

    bool initialize(const SimConfig& config) {
        if (initialized) {
            shutdown();
        }

        enabled = config.acceleration.enable_tidal;
        if (!enabled) {
            std::cout << "TidalAccelerationManager: Disabled" << std::endl;
            initialized = true;
            return true;
        }

        // Store patch offset (SURFACE mode only).
        // In MASS_CENTER mode, particle positions are already relative to COM
        // in J2000 frame — no offset needed.
        if (config.coord_system == CoordinateSystem::SURFACE) {
            offset_x = config.domain.surface_origin.x;
            offset_y = config.domain.surface_origin.y;
            offset_z = config.domain.surface_origin.z;
        } else {
            offset_x = 0.0;
            offset_y = 0.0;
            offset_z = 0.0;
        }

        load_method = config.acceleration.tidal_load_method;
        perturber_mass = config.acceleration.perturber_mass;

        // Open data file
        const char* path = config.acceleration.tidal_data_path;
        if (path[0] == '\0') {
            std::cerr << "ERROR: No tidal data path specified" << std::endl;
            return false;
        }

        data_file.open(path, std::ios::binary);
        if (!data_file.is_open()) {
            std::cerr << "ERROR: Cannot open tidal data file: " << path << std::endl;
            return false;
        }

        // Read header
        data_file.read(reinterpret_cast<char*>(&header), sizeof(header));

        if (!data_file || memcmp(header.magic, "EARTHPOS", 8) != 0 || header.version != 1 ||
            header.num_frames == 0 || header.num_frames > 100000000 ||
            !std::isfinite(header.time_start) || !std::isfinite(header.time_interval) ||
            header.time_interval <= 0.0f || !std::isfinite(header.perturber_mass) ||
            header.perturber_mass <= 0.0) {
            std::cerr << "ERROR: Invalid Earth position data file format" << std::endl;
            data_file.close();
            return false;
        }
        data_file.seekg(0, std::ios::end);
        const std::streamoff expected = static_cast<std::streamoff>(sizeof(EarthPositionHeader)) +
            static_cast<std::streamoff>(header.num_frames) * sizeof(EarthPositionFrame);
        if (data_file.tellg() != expected) {
            std::cerr << "ERROR: EARTHPOS v1 file has a truncated payload or trailing bytes" << std::endl;
            data_file.close();
            return false;
        }
        data_file.seekg(sizeof(EarthPositionHeader), std::ios::beg);

        // The binary header is authoritative, but YAML must declare the same
        // body rather than silently changing the physical problem.
        if (!std::isfinite(perturber_mass) || perturber_mass <= 0.0 ||
            std::fabs(perturber_mass - header.perturber_mass) >
                1e-12 * std::max(std::fabs(perturber_mass), std::fabs(header.perturber_mass))) {
            std::cerr << "ERROR: EARTHPOS header mass does not match acceleration.perturber_mass" << std::endl;
            data_file.close();
            return false;
        }
        perturber_mass = header.perturber_mass;

        // Initialize buffer
        earth_buffer.total_frames = header.num_frames;
        earth_buffer.time_start = header.time_start;
        earth_buffer.time_interval = header.time_interval;
        earth_buffer.perturber_mass = perturber_mass;

        // Determine batch size based on load method
        if (load_method == LoadMethod::ONCE) {
            earth_buffer.allocate(header.num_frames);
            load_all_data();
        } else {
            int32_t batch = static_cast<int32_t>(
                config.acceleration.tidal_time_interval / header.time_interval);
            batch = std::max(100, batch);
            earth_buffer.allocate(batch);
        }

        initialized = true;

        const char* frame_label;
        if (config.coord_system == CoordinateSystem::SURFACE)
            frame_label = "body-fixed";
        else if (config.coord_system == CoordinateSystem::ROTATING)
            frame_label = "rotating (constant omega)";
        else
            frame_label = "J2000 (inertial)";
        std::cout << "TidalAccelerationManager initialized:" << std::endl;
        std::cout << "  Coordinate frame: " << frame_label << std::endl;
        std::cout << "  Data frames: " << header.num_frames << std::endl;
        std::cout << "  Time interval: " << header.time_interval << " s" << std::endl;
        std::cout << "  Perturber mass: " << perturber_mass << " kg" << std::endl;
        std::cout << "  Patch offset: (" << offset_x << ", " << offset_y
                  << ", " << offset_z << ") m" << std::endl;

        return true;
    }

    // =========================================================================
    // Data Loading
    // =========================================================================

    void load_all_data() {
        if (data_loaded) return;

        int32_t num_frames = header.num_frames;

        // Seek to data section
        data_file.seekg(sizeof(EarthPositionHeader));

        // Read all frames
        for (int32_t i = 0; i < num_frames; ++i) {
            EarthPositionFrame frame;
            data_file.read(reinterpret_cast<char*>(&frame), sizeof(EarthPositionFrame));
            if (!data_file || !std::isfinite(frame.R_c_x) || !std::isfinite(frame.R_c_y) ||
                !std::isfinite(frame.R_c_z) || !std::isfinite(frame.R_c_mag) || frame.R_c_mag <= 0.0)
                throw std::runtime_error("EARTHPOS v1 frame is truncated or invalid");
            const double magnitude = std::sqrt(frame.R_c_x * frame.R_c_x + frame.R_c_y * frame.R_c_y + frame.R_c_z * frame.R_c_z);
            if (std::fabs(magnitude - frame.R_c_mag) > 1e-12 * std::max(magnitude, frame.R_c_mag))
                throw std::runtime_error("EARTHPOS v1 magnitude does not match position");

            earth_buffer.h_times[i] = header.time_start + i * header.time_interval;
            earth_buffer.h_R_c_x[i] = frame.R_c_x;
            earth_buffer.h_R_c_y[i] = frame.R_c_y;
            earth_buffer.h_R_c_z[i] = frame.R_c_z;
            earth_buffer.h_R_c_mag[i] = frame.R_c_mag;

            // Recompute magnitude if not provided
            if (frame.R_c_mag <= 0) {
                earth_buffer.h_R_c_mag[i] = sqrt(frame.R_c_x * frame.R_c_x +
                                                  frame.R_c_y * frame.R_c_y +
                                                  frame.R_c_z * frame.R_c_z);
            }
        }

        earth_buffer.loaded_start_frame = 0;
        earth_buffer.loaded_num_frames = num_frames;
        data_loaded = true;

        // Print closest approach info
        double min_dist = 1.0e20;
        int min_frame = 0;
        for (int32_t i = 0; i < num_frames; ++i) {
            if (earth_buffer.h_R_c_mag[i] < min_dist) {
                min_dist = earth_buffer.h_R_c_mag[i];
                min_frame = i;
            }
        }
        std::cout << "Loaded " << num_frames << " Earth position frames" << std::endl;
        std::cout << "  Closest approach: " << (min_dist / 1000.0) << " km at frame "
                  << min_frame << std::endl;
    }

    void load_batch(int start_frame) {
        start_frame = std::max(0, std::min(start_frame,
                               earth_buffer.total_frames - earth_buffer.batch_size));
        int num_to_load = std::min(earth_buffer.batch_size,
                                   earth_buffer.total_frames - start_frame);

        size_t data_offset = sizeof(EarthPositionHeader) +
                             start_frame * sizeof(EarthPositionFrame);
        data_file.seekg(data_offset);

        for (int i = 0; i < num_to_load; ++i) {
            EarthPositionFrame frame;
            data_file.read(reinterpret_cast<char*>(&frame), sizeof(EarthPositionFrame));
            if (!data_file || !std::isfinite(frame.R_c_x) || !std::isfinite(frame.R_c_y) ||
                !std::isfinite(frame.R_c_z) || !std::isfinite(frame.R_c_mag) || frame.R_c_mag <= 0.0)
                throw std::runtime_error("EARTHPOS v1 frame is truncated or invalid");
            const double magnitude = std::sqrt(frame.R_c_x * frame.R_c_x + frame.R_c_y * frame.R_c_y + frame.R_c_z * frame.R_c_z);
            if (std::fabs(magnitude - frame.R_c_mag) > 1e-12 * std::max(magnitude, frame.R_c_mag))
                throw std::runtime_error("EARTHPOS v1 magnitude does not match position");

            earth_buffer.h_times[i] = header.time_start +
                                      (start_frame + i) * header.time_interval;
            earth_buffer.h_R_c_x[i] = frame.R_c_x;
            earth_buffer.h_R_c_y[i] = frame.R_c_y;
            earth_buffer.h_R_c_z[i] = frame.R_c_z;
            earth_buffer.h_R_c_mag[i] = frame.R_c_mag;

            if (frame.R_c_mag <= 0) {
                earth_buffer.h_R_c_mag[i] = sqrt(frame.R_c_x * frame.R_c_x +
                                                  frame.R_c_y * frame.R_c_y +
                                                  frame.R_c_z * frame.R_c_z);
            }
        }

        earth_buffer.loaded_start_frame = start_frame;
        earth_buffer.loaded_num_frames = num_to_load;
    }

    void update_prefetch(double current_time) {
        if (load_method == LoadMethod::ONCE) return;
        if (!data_file.is_open()) return;

        float rel_time = (static_cast<float>(current_time) - earth_buffer.time_start) /
                         earth_buffer.time_interval;
        int needed_frame = static_cast<int>(rel_time);

        bool need_load = false;
        if (earth_buffer.loaded_start_frame < 0) {
            need_load = true;
        } else {
            int frames_ahead = (earth_buffer.loaded_start_frame +
                               earth_buffer.loaded_num_frames) - needed_frame;
            if (frames_ahead < earth_buffer.batch_size / 4) {
                need_load = true;
            }
        }

        if (need_load) {
            int start_frame = std::max(0, needed_frame - earth_buffer.batch_size / 4);
            load_batch(start_frame);
        }
    }

    // =========================================================================
    // Compute
    // =========================================================================

    void compute(
        SimulationState& state,
        const SimConfig& config,
        double current_time,
        cudaStream_t stream
    ) {
        if (!initialized || !enabled) return;

        int32_t num_particles = state.particles.num_particles;
        if (num_particles == 0) return;

        // Update prefetch
        update_prefetch(current_time);

        // Interpolate Earth position at current time
        earth_buffer.interpolate_at_time(static_cast<float>(current_time));

        // Prepare GPU parameters
        TidalParamsGPU params;
        params.R_c_x = earth_buffer.current_R_c_x;
        params.R_c_y = earth_buffer.current_R_c_y;
        params.R_c_z = earth_buffer.current_R_c_z;
        params.R_c_mag = earth_buffer.current_R_c_mag;
        params.R_c_mag_squared = params.R_c_mag * params.R_c_mag;
        params.R_c_mag_cubed = params.R_c_mag_squared * params.R_c_mag;

        // G = 6.67430e-11 m³/(kg·s²)
        params.G = GRAVITATIONAL_CONSTANT;
        params.perturber_mass = perturber_mass;

        // Tidal factor: G * M_E / R_c³
        params.tidal_factor = GRAVITATIONAL_CONSTANT * perturber_mass / params.R_c_mag_cubed;

        params.offset_x = offset_x;
        params.offset_y = offset_y;
        params.offset_z = offset_z;
        params.enabled = true;

        // Upload to constant memory
        cudaMemcpyToSymbolAsync(dev_tidal_params, &params,
                                sizeof(TidalParamsGPU), 0,
                                cudaMemcpyHostToDevice, stream);

        // Launch kernel
        int block_size = config.gpu.block_size;
        int num_blocks = (num_particles + block_size - 1) / block_size;

        compute_tidal_acceleration_kernel<<<num_blocks, block_size, 0, stream>>>(
            state.particles.pos_x, state.particles.pos_y, state.particles.pos_z,
            state.particles.mass,
            state.particles.force_x, state.particles.force_y, state.particles.force_z,
            num_particles
        );
    }

    // =========================================================================
    // Shutdown
    // =========================================================================

    void shutdown() {
        if (data_file.is_open()) {
            data_file.close();
        }
        earth_buffer.clear();
        enabled = false;
        initialized = false;
        data_loaded = false;
    }
};

// =============================================================================
// Static Instance
// =============================================================================

static TidalAccelerationManager g_tidal_manager;

// =============================================================================
// AccelerationManager Integration
// =============================================================================

void AccelerationManager::compute_tidal(
    SimulationState& state,
    const SimConfig& config,
    double current_time,
    cudaStream_t stream
) {
    // Initialize on first call
    static bool tidal_initialized = false;
    if (!tidal_initialized) {
        if (!g_tidal_manager.initialize(config))
            throw std::runtime_error("failed to initialize EARTHPOS/tidal acceleration");
        tidal_initialized = true;
    }

    g_tidal_manager.compute(state, config, current_time, stream);
}

