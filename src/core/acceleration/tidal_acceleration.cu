// Write Earth position data binary file
inline void write_earth_position_binary(
    const std::string& output_path,
    const std::vector<float>& times,
    const std::vector<double>& R_c_x,
    const std::vector<double>& R_c_y,
    const std::vector<double>& R_c_z,
    double perturber_mass = 5.972e24
) {
    std::ofstream file(output_path, std::ios::binary);
    if (!file.is_open()) {
        throw std::runtime_error("Cannot create Earth position file: " + output_path);
    }

    int32_t num_frames = static_cast<int32_t>(times.size());
    float time_interval = (num_frames > 1) ? (times[1] - times[0]) : 60.0f;

    EarthPositionHeader header;
    header.num_frames = num_frames;
    header.time_start = times[0];
    header.time_interval = time_interval;
    header.perturber_mass = perturber_mass;

    file.write(reinterpret_cast<const char*>(&header), sizeof(header));

    for (int32_t i = 0; i < num_frames; ++i) {
        EarthPositionFrame frame;
        frame.R_c_x = R_c_x[i];
        frame.R_c_y = R_c_y[i];
        frame.R_c_z = R_c_z[i];
        frame.R_c_mag = sqrt(R_c_x[i] * R_c_x[i] +
                             R_c_y[i] * R_c_y[i] +
                             R_c_z[i] * R_c_z[i]);
        file.write(reinterpret_cast<const char*>(&frame), sizeof(frame));
    }

    file.close();
    std::cout << "Wrote " << num_frames << " frames to " << output_path << std::endl;
}

// Compute peak tidal acceleration (for validation)
inline double compute_peak_tidal_acceleration(
    double closest_approach_distance,  // meters
    double perturber_mass = 5.972e24,   // kg
    double asteroid_radius = 170.0      // meters (Apophis effective radius)
) {
    // At closest approach, tidal acceleration at surface:
    // a_peak ≈ 2 * G * M_E * R_asteroid / R_c³
    double R_c_cubed = closest_approach_distance * closest_approach_distance *
                       closest_approach_distance;
    double a_peak = 2.0 * GRAVITATIONAL_CONSTANT * perturber_mass *
                    asteroid_radius / R_c_cubed;

    return a_peak;
}

// Print tidal statistics
inline void print_tidal_statistics(
    double closest_approach_km,
    double perturber_mass = 5.972e24
) {
    double closest_approach_m = closest_approach_km * 1000.0;

    std::cout << "=== Tidal Acceleration Statistics ===" << std::endl;
    std::cout << "Closest approach: " << closest_approach_km << " km" << std::endl;
    std::cout << "Perturber mass: " << perturber_mass << " kg" << std::endl;

    double a_peak = compute_peak_tidal_acceleration(closest_approach_m, perturber_mass);
    std::cout << "Peak tidal acceleration: " << a_peak << " m/s²" << std::endl;
    std::cout << "  = " << (a_peak * 1e6) << " μm/s²" << std::endl;

    // Compare to Apophis surface gravity (~10⁻⁵ g)
    double apophis_g = 1.0e-5 * 9.81;  // Approximate
    std::cout << "  = " << (a_peak / apophis_g) << " × Apophis surface gravity" << std::endl;

    std::cout << "=====================================" << std::endl;
}

