// =============================================================================
// Tidal Acceleration for DEM Simulation
// =============================================================================
// Implements gravitational perturbation from external body (e.g., Earth):
//
// Tidal acceleration formula (Equation A3):
//   a_t = (G * M_E / R_c³) * (r - 3 * ((R_c + r) · r / R_c²) * R_c)
//
// Where:
//   G   = Gravitational constant (6.67430e-11 m³/(kg·s²))
//   M_E = Perturber mass (Earth = 5.972e24 kg)
//   R_c = Position of perturber (Earth) relative to Apophis center of mass
//   r   = Position of particle relative to Apophis center of mass
//
// COORDINATE FRAME CONVENTIONS (by simulation coordinate_system):
//
// MASS_CENTER mode (whole-body, e.g. Apophis flyby): J2000 inertial frame
// - r = particle_position (COM at origin, no offset)
// - R_c from binary file in J2000 frame
//   → generated by pre_calculate_earth_distance.py from JPL Horizons ephemeris
//   → dot products valid because both vectors share the same inertial frame
// - Rationale: rubble-pile asteroid has no single rigid body-fixed frame
//
// SURFACE mode (local patch): body-fixed frame
// - r = surface_origin + particle_position
// - R_c from binary file in body-fixed frame
//   → requires J2000-to-body-fixed coordinate transformation (attitude matrix)
//
// Data Loading Strategy:
// - Earth position (R_c) pre-calculated from ephemeris data
// - Data interval: 60s (configurable via YAML)
// - Load all data at startup (LoadMethod::ONCE) for short simulations
// - Or batch load for long simulations
// - Linear interpolation in time to Verlet timestep
//
// Physical Context (Apophis 2029 Flyby):
// - Closest approach: ~31,000 km from Earth's surface
// - Tidal forces cause surface slope changes and potential landslides
// - Peak tidal stress ~8 hours around closest approach
//
// Reference: Equation (A3) in asteroid dynamics literature
// =============================================================================

