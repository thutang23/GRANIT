#!/usr/bin/env python3
"""Print a compiler-evaluated inventory of configuration constructor defaults.

Requires a host C++17 compiler and CUDA headers; it does not invoke nvcc or a GPU.
Runtime normalization and required material data are explained in Configuration_Defaults.md.
"""
import argparse
from pathlib import Path
import re
import subprocess
import tempfile

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--cuda-root', default='/usr/local/cuda-12.1')
parser.add_argument('--cxx', default='c++')
parser.add_argument('--yaml-include', required=True, help='yaml-cpp include directory')
args = parser.parse_args()
root = Path(__file__).resolve().parents[1]
header = root / 'src/core/constant/command_line_interface.h'
text = header.read_text()
text += (root / 'src/core/sph/sph_stage_math.h').read_text()
material = (root / 'src/core/material/material_database.h').read_text()
text += re.search(r'struct MaterialDatabaseInfo \{.*?^};', material, flags=re.S | re.M).group(0)
text = re.sub(r'//[^\n]*|/\*.*?\*/', '', text, flags=re.S)
code = r'''
#include "src/core/constant/command_line_interface.h"
#include <iostream>
#include <iomanip>
#include <type_traits>
using namespace cudadem;
template<class T> void show(const T& value) {
    if constexpr (std::is_same_v<T, bool>) std::cout << (value ? "true" : "false");
    else if constexpr (std::is_enum_v<T>) std::cout << static_cast<int>(value);
    else if constexpr (std::is_arithmetic_v<T>) std::cout << +value;
    else if constexpr (std::is_pointer_v<T>) std::cout << (value ? "non-null" : "null");
    else std::cout << "nested record";
}
template<size_t N> void show(const char (&value)[N]) { std::cout << '"' << value << '"'; }
template<class T, size_t N> void show(const T (&value)[N]) {
    std::cout << '[';
    for(size_t i=0;i<N;++i) { if(i) std::cout << ", "; show(value[i]); }
    std::cout << ']';
}
void show(const Vec3d& v) { std::cout << '[' << v.x << ", " << v.y << ", " << v.z << ']'; }
void show(const Vec3f& v) { std::cout << '[' << v.x << ", " << v.y << ", " << v.z << ']'; }
void show(const Mat3d& v) { show(v.data); }
int main() { std::cout << std::setprecision(9);
'''
count = 0
for name, body in re.findall(r'struct (\w+)\s*\{(.*?)^};', text, flags=re.S | re.M):
    if name in {'Vec3d', 'Vec3f', 'Mat3d'}:
        continue
    declarations = body.split('__host__')[0]
    fields = re.findall(r'^\s*([\w:]+\s*\*?)\s+(\w+)\s*(?:\[[^;]+?\])?\s*(?:=[^;]+)?;', declarations, flags=re.M)
    code += '\n{ ' + name + ' config{};\n'
    for typ, field in fields:
        # Variable-size records and homogeneous fixed record arrays are covered
        # by their own constructor entries, not hundreds of repeated rows.
        label = f'{name}.{field}'
        if typ.strip().endswith('Config') or typ.strip() in {'ClumpTemplate', 'ClumpInstance', 'MaterialDatabaseInfo', 'SphStageParameters'}:
            code += f'std::cout << "| `{label}` | see `{typ.strip()}` |\\n";\n'
        else:
            code += f'std::cout << "| `{label}` | "; show(config.{field}); std::cout << " |\\n";\n'
        count += 1
    code += '}\n'
code += '}\n'
with tempfile.TemporaryDirectory(prefix='granit-default-inventory-') as tmp:
    tmp = Path(tmp)
    (tmp / 'inventory.cpp').write_text(code)
    subprocess.run([args.cxx, '-std=c++17', '-I'+str(root), '-I'+args.cuda_root+'/include', '-I'+args.yaml_include,
                    str(tmp/'inventory.cpp'), '-o', str(tmp/'inventory')], check=True)
    output = subprocess.check_output([str(tmp/'inventory')], text=True)
print('# Configuration constructor inventory\n')
print(f'Generated by `tools/audit_config_defaults.py`: {count} members. Enum values use')
print('their numeric declarations in `command_line_interface.h`. These are raw')
print('constructor values, including internal/derived members, not a YAML template.')
print('See [Configuration_Defaults.md](Configuration_Defaults.md) for mode-dependent')
print('normalization, required inputs, and the audit conclusions. Material properties')
print('are loaded from the material database; internal placeholders do not supply them.\n')
print('| Internal member | Constructor default |\n| --- | --- |')
print(output, end='')
